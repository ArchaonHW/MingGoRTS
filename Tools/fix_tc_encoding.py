def fix_file(filepath, backup_dir):
    try:
        # Try UTF-8 first
        try:
            with open(filepath, 'r', encoding='utf-8') as f:
                content = f.read()
        except UnicodeDecodeError:
            # Try with different encodings
            for enc in ['gbk', 'big5', 'gb2312', 'gb18030', 'cp950']:
                try:
                    with open(filepath, 'r', encoding=enc) as f:
                        content = f.read()
                    break
                except:
                    continue
            else:
                print(f"  Skipping (encoding issues): {filepath}")
                return False
        
        original = content
        modified = False
        
        # Apply replacements
        for old, new in tc_replacements.items():
            if old in content:
                content = content.replace(old, new)
                modified = True
        
        if modified:
            # Backup
            filename = os.path.basename(filepath)
            backup_path = os.path.join(backup_dir, filename + ".bak")
            shutil.copy2(filepath, backup_path)
            
            # Write
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            
            return True
        
        return False
    except Exception as e:
        print(f"  Error: {filepath} - {e}")
        return False

def main():
    root = r"C:\HW\MingGoRTS"
    backup_dir = os.path.join(root, "Backup_GarbledFix_v2")
    os.makedirs(backup_dir, exist_ok=True)
    
    # Get all header files
    header_files = list(Path(root).rglob("*.h"))
    total = len(header_files)
    fixed = 0
    errors = 0
    
    print(f"Scanning {total} header files...")
    print("-" * 60)
    
    for i, fp in enumerate(header_files, 1):
        if i % 50 == 0:
            print(f"  Progress: {i}/{total} ({i/total*100:.1f}%)")
        
        try:
            if fix_file(str(fp), backup_dir):
                print(f"  Fixed: {fp.name}")
                fixed += 1
        except Exception as e:
            errors += 1
            print(f"  Error processing {fp}: {e}")
    
    print("-" * 60)
    print(f"Complete! Fixed {fixed} files, {errors} errors")
    print(f"Backup: {backup_dir}")

if __name__ == "__main__":
    main()
