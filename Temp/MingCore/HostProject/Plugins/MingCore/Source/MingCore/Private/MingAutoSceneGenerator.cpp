UMingAutoSceneGenerator::UMingAutoSceneGenerator()
    : bIsInitialized(false)
    , bPreviewActive(false)
    , TotalSceneCount(0)
    , TotalGenerationTime(0.0f)
    , DefaultQuality(EGenerationQuality::Standard)
    , DefaultStyle(ESceneStyle::Realistic)
    , OutputDirectory(TEXT("/Game/AutoGenerated/Scenes/"))
{
}

void UMingAutoSceneGenerator::InitializeAutoSceneGenerator()
{
    if (bIsInitialized)
    {
        UE_LOG(LogTemp, Warning, TEXT("Auto Scene Generator already initialized"));
        return;
    }

    // 初始化AI內容管理器
    AIContentManager = NewObject<UMingAIContentManager>();
    if (AIContentManager)
    {
        AIContentManager->InitializeAIContentManager();
    }

    // 加載默認模板
    LoadDefaultTemplates();

    // 加載場景數據
    LoadSceneData();

    bIsInitialized = true;
    UE_LOG(LogTemp, Log, TEXT("Auto Scene Generator initialized"));
}

FString UMingAutoSceneGenerator::GenerateScene(const FSceneRequirement& Requirements)
{
    if (!bIsInitialized)
    {
        UE_LOG(LogTemp, Error, TEXT("Auto Scene Generator not initialized"));
        return TEXT("");
    }

    FString SceneName = GenerateUniqueSceneName();
    
    // 創建場景記錄
    FGeneratedScene NewScene;
    NewScene.SceneName = SceneName;
    NewScene.ScenePath = GetScenePath(SceneName);
    NewScene.bIsComplete = false;
    NewScene.GenerationProgress = 0.0f;
    NewScene.GenerationTime = FDateTime::Now();
    
    GeneratedScenes.Add(SceneName, NewScene);
    
    // 通知開始生成
    NotifySceneGenerationStarted(SceneName, Requirements);
    
    // 開始異步生成
    AsyncTask(ENamedThreads::AnyBackgroundThreadNormalTask, [this, SceneName, Requirements]()
    {
        ProcessSceneGeneration(SceneName, Requirements);
    });
    
    return SceneName;
}

void UMingAutoSceneGenerator::GenerateSceneAsync(const FSceneRequirement& Requirements)
{
    GenerateScene(Requirements);
}

TArray<FString> UMingAutoSceneGenerator::GenerateMultipleScenes(const TArray<FSceneRequirement>& RequirementsList)
{
    TArray<FString> SceneNames;
    
    for (const FSceneRequirement& Requirements : RequirementsList)
    {
        FString SceneName = GenerateScene(Requirements);
        if (!SceneName.IsEmpty())
        {
            SceneNames.Add(SceneName);
        }
    }
    
    return SceneNames;
}

