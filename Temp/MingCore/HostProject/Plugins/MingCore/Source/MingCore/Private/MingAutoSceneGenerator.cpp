void UMingAutoSceneGenerator::ProcessSceneGeneration(const FString& SceneName, const FSceneRequirement& Requirements)
{
    if (!GeneratedScenes.Contains(SceneName))
    {
        return;
    }
    
    FGeneratedScene& Scene = GeneratedScenes[SceneName];
    
    try
    {
        // 更新進度
        UpdateGenerationProgress(SceneName, 0.1f);
        
        // 生成所需資產
        GenerateRequiredAssets(SceneName, Requirements);
        
        UpdateGenerationProgress(SceneName, 0.7f);
        
        // 設置場景配置
        SetupSceneConfiguration(SceneName, Requirements);
        
        UpdateGenerationProgress(SceneName, 0.9f);
        
        // 生成縮略圖
        GenerateSceneThumbnail(SceneName);
        
        UpdateGenerationProgress(SceneName, 1.0f);
        
        // 完成生成
        CompleteSceneGeneration(SceneName, true);
    }
    catch (...)
    {
        CompleteSceneGeneration(SceneName, false);
    }
}

void UMingAutoSceneGenerator::GenerateRequiredAssets(const FString& SceneName, const FSceneRequirement& Requirements)
{
    if (!AIContentManager)
    {
        return;
    }
    
    FGeneratedScene& Scene = GeneratedScenes[SceneName];
    
    for (EAIContentType AssetType : Requirements.RequiredAssets)
    {
        if (Requirements.AssetPrompts.Contains(AssetType))
        {
            FString Prompt = Requirements.AssetPrompts[AssetType];
            FString AssetPath = AIContentManager->GenerateContent(AssetType, Prompt, DefaultQuality);
            
            if (!AssetPath.IsEmpty())
            {
                Scene.GeneratedAssets.Add(AssetType, AssetPath);
            }
        }
    }
}

void UMingAutoSceneGenerator::SetupSceneConfiguration(const FString& SceneName, const FSceneRequirement& Requirements)
{
    FGeneratedScene& Scene = GeneratedScenes[SceneName];
    
    // 創建場景配置
    Scene.SceneConfiguration = CreateSceneConfiguration(Requirements);
    
    if (AIContentManager)
    {
        AIContentManager->GenerateGameScene(Requirements.Description, Scene.SceneConfiguration);
    }
}

void UMingAutoSceneGenerator::CompleteSceneGeneration(const FString& SceneName, bool bSuccess)
{
    if (!GeneratedScenes.Contains(SceneName))
    {
        return;
    }
    
    FGeneratedScene& Scene = GeneratedScenes[SceneName];
    Scene.bIsComplete = bSuccess;
    
    if (bSuccess)
    {
        TotalSceneCount++;
        NotifySceneGenerationCompleted(SceneName, Scene);
    }
    else
    {
        NotifySceneGenerationFailed(SceneName, TEXT("Scene generation failed"));
    }
    
    // 從活動生成列表中移除
    ActiveGenerations.Remove(SceneName);
}

void UMingAutoSceneGenerator::UpdateGenerationProgress(const FString& SceneName, float Progress)
{
    if (GeneratedScenes.Contains(SceneName))
    {
        GeneratedScenes[SceneName].GenerationProgress = Progress;
        NotifySceneGenerationProgress(SceneName, Progress);
    }
}

