TArray<FGeneratedScene> UMingAutoSceneGenerator::GetAllGeneratedScenes() const
{
    TArray<FGeneratedScene> AllScenes;
    
    for (const auto& ScenePair : GeneratedScenes)
    {
        AllScenes.Add(ScenePair.Value);
    }
    
    return AllScenes;
}

FGeneratedScene UMingAutoSceneGenerator::GetGeneratedScene(const FString& SceneName) const
{
    if (GeneratedScenes.Contains(SceneName))
    {
        return GeneratedScenes[SceneName];
    }
    
    return FGeneratedScene();
}

void UMingAutoSceneGenerator::DeleteGeneratedScene(const FString& SceneName)
{
    if (GeneratedScenes.Contains(SceneName))
    {
        GeneratedScenes.Remove(SceneName);
        
        // 刪除相關文件
        FString ScenePath = GetScenePath(SceneName);
        IPlatformFile& PlatformFile = FPlatformFileManager::Get().GetPlatformFile();
        if (PlatformFile.DirectoryExists(*ScenePath))
        {
            PlatformFile.DeleteDirectoryRecursively(*ScenePath);
        }
        
        UE_LOG(LogTemp, Log, TEXT("Deleted generated scene: %s"), *SceneName);
    }
}

void UMingAutoSceneGenerator::LoadSceneIntoWorld(const FString& SceneName, UWorld* World)
{
    if (!World || !GeneratedScenes.Contains(SceneName))
    {
        UE_LOG(LogTemp, Warning, TEXT("Cannot load scene %s: invalid world or scene not found"), *SceneName);
        return;
    }
    
    const FGeneratedScene& Scene = GeneratedScenes[SceneName];
    
    // 加載場景配置
    if (AIContentManager)
    {
        AIContentManager->GenerateGameScene(Scene.SceneConfiguration.SceneDescription, Scene.SceneConfiguration);
    }
    
    UE_LOG(LogTemp, Log, TEXT("Loaded scene %s into world"), *SceneName);
}

void UMingAutoSceneGenerator::StartScenePreview(const FString& SceneName)
{
    if (!GeneratedScenes.Contains(SceneName))
    {
        UE_LOG(LogTemp, Warning, TEXT("Scene %s not found for preview"), *SceneName);
        return;
    }
    
    CurrentPreviewScene = SceneName;
    
    if (AIContentManager)
    {
        AIContentManager->StartRealTimePreview();
    }
    
    bPreviewActive = true;
    
    UE_LOG(LogTemp, Log, TEXT("Started preview for scene: %s"), *SceneName);
}

void UMingAutoSceneGenerator::StopScenePreview()
{
    if (AIContentManager)
    {
        AIContentManager->StopRealTimePreview();
    }
    
    bPreviewActive = false;
    CurrentPreviewScene = TEXT("");
    
    UE_LOG(LogTemp, Log, TEXT("Stopped scene preview"));
}

